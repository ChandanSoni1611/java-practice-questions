public class sum_of_natural_numbers {
    public static void main(String[] args) {
        System.out.println("sum of nautral number");

        int num = 5;
        int sum = 0 ;
        int i ;
        for(i = 0; i <= num; i++){
            sum = sum + i;
        }
        System.out.println(sum);
    }
}
